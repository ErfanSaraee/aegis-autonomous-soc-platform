"""Pydantic v2 schemas and Structured JSON Output contracts for the AEGIS Autonomous SOC Platform."""

from datetime import datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from app.models.soc_models import (
    IncidentSeverity,
    IncidentStatus,
    LLMProviderChoice,
    MITRETactic,
)


class SIEMTelemetryIngestRequest(BaseModel):
    """Incoming SIEM / EDR / Firewall telemetry payload submitted for autonomous SOC investigation."""

    title: str = Field(
        ...,
        min_length=5,
        max_length=220,
        description="Short alert headline generated by SIEM or EDR sensor.",
        examples=[
            "Suspicious PowerShell Encoded Command & Lateral Movement SMB Beacon"],
    )
    source_ip: str = Field(
        default="185.220.101.42",
        description="Originating IPv4/IPv6 address.",
    )
    target_host: str = Field(
        default="prod-db-cluster-01.corp.internal",
        description="Target enterprise hostname or asset identifier.",
    )
    event_source: str = Field(
        default="CrowdStrike_EDR_&_Suricata_NIDS",
        description="Telemetry sensor source.",
    )
    raw_log_payload: str = Field(
        ...,
        min_length=10,
        max_length=20000,
        description="Raw SIEM log lines, process command lines, HTTP headers, or network flow logs.",
    )
    network_bytes_out: int = Field(
        default=48500,
        ge=0,
        description="Outbound bytes transferred during flow window.",
    )
    failed_auth_count: int = Field(
        default=0,
        ge=0,
        description="Number of failed authentication attempts in window.",
    )
    process_entropy_score: float = Field(
        default=4.1,
        ge=0.0,
        le=8.0,
        description="Observed command-line entropy from endpoint sensor.",
    )
    preferred_llm_provider: LLMProviderChoice = Field(
        default=LLMProviderChoice.ANTHROPIC,
        description="Target foundation model provider (Anthropic, OpenAI, Gemini, Ollama, vLLM).",
    )


class NeuralAnomalyReport(BaseModel):
    """Telemetry from PyTorch Autoencoder/Attention, XGBoost Classifier, and IsolationForest."""

    pytorch_reconstruction_error: float
    pytorch_attention_score: float
    top_salient_log_tokens: dict[str, float]
    xgboost_threat_probability: float
    isolation_forest_anomaly: bool
    composite_anomaly_score: float = Field(..., ge=0.0, le=1.0)
    predicted_severity: IncidentSeverity


class LogGuardrailReport(BaseModel):
    """Zero-Trust Guardrail report for adversarial Log-Embedded Prompt Injection & PII masking."""

    log_injection_detected: bool
    shannon_entropy: float
    is_obfuscated_payload: bool
    pii_redacted_entities: list[str]
    sanitized_log_payload: str
    guardrail_notes: list[str]


class MITREIntelligenceHit(BaseModel):
    """Single hybrid retrieval document from pgvector/Pinecone/ChromaDB + BM25 Reciprocal Rank Fusion."""

    technique_id: str
    technique_name: str
    tactic: MITRETactic
    rrf_score: float
    dense_vector_score: float
    bm25_lexical_score: float
    description: str
    recommended_countermeasure: str


class ASTPlaybookVerification(BaseModel):
    """Formal Python AST static verification result for generated SOAR remediation scripts."""

    is_safe: bool
    cyclomatic_complexity: int
    violations: list[str]
    inspected_nodes: list[str]


class DSPyTriageCalibration(BaseModel):
    """DSPy declarative prompt compiler output calibrating false-positive likelihood & severity."""

    false_positive_likelihood: float = Field(..., ge=0.0, le=1.0)
    calibrated_confidence: float = Field(..., ge=0.0, le=1.0)
    compiled_triage_rationale: str
    applied_security_invariants: list[str]


class AgentExecutionStep(BaseModel):
    """Single structured trace event emitted by a LangGraph or CrewAI SOC agent."""

    step_index: int
    agent_name: str
    framework: str
    protocol: str
    status: str
    summary: str
    latency_ms: float


class SOCIncidentResponse(BaseModel):
    """Complete end-to-end autonomous SOC investigation and SOAR response contract."""

    model_config = ConfigDict(from_attributes=True)

    incident_id: str
    title: str
    source_ip: str
    target_host: str
    event_source: str
    severity: IncidentSeverity
    status: IncidentStatus
    llm_provider_used: LLMProviderChoice

    neural_anomaly: NeuralAnomalyReport
    log_guardrail: LogGuardrailReport
    mitre_tactic: MITRETactic
    mitre_technique_id: str
    cti_rag_hits: list[MITREIntelligenceHit]
    crewai_osint_report: str
    dspy_calibration: DSPyTriageCalibration

    executive_rca_summary: str
    remediation_actions: list[str]
    soar_python_playbook: str
    ast_verification: ASTPlaybookVerification
    hitl_approval_required: bool
    agent_trace: list[AgentExecutionStep]
    created_at: datetime


class HITLApprovalRequest(BaseModel):
    """Human-in-the-Loop (HITL) commander approval or rejection for high-impact SOAR containment."""

    responder_name: str = Field(default="Erfan Saraee (Lead SOC Commander)")
    approve_containment: bool = Field(default=True)
    commander_notes: str = Field(
        default="Verified MITRE ATT&CK chain and AST-safe SOAR script. Approved host isolation and firewall block."
    )


class SOCDashboardMetricsResponse(BaseModel):
    """Aggregated KPI metrics for the Next.js SOC Command Center frontend."""

    total_incidents_analyzed: int
    critical_p0_count: int
    auto_contained_count: int
    awaiting_hitl_count: int
    false_positives_filtered: int
    log_injections_blocked: int
    mean_time_to_respond_ms: float
    mitre_tactic_distribution: dict[str, int]
    recent_incidents: list[dict[str, Any]]
